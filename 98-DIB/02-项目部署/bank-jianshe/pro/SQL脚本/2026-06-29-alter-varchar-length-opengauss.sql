-- 查询所有varchar类型字段
SELECT
    table_name                          AS "表名",
    column_name                         AS "字段名",
    character_maximum_length            AS "最大字符长度",
    is_nullable                         AS "是否可空",
    column_default                      AS "默认值"
FROM information_schema.columns
WHERE table_schema = 'dib_report_copilot'
  AND data_type = 'character varying'
ORDER BY table_name, ordinal_position;



-- 批量生成alter语句
SELECT
    FORMAT(
            'ALTER TABLE %I.%I ALTER COLUMN %I TYPE VARCHAR(%s);',
            table_schema,
            table_name,
            column_name,
            character_maximum_length * 4
    ) AS alter_sql
FROM information_schema.columns
WHERE table_schema = 'dib_report_copilot'
  AND data_type = 'character varying'
  AND character_maximum_length IS NOT NULL   -- 排除 varchar 无长度限制的情况
ORDER BY table_name, ordinal_position;



